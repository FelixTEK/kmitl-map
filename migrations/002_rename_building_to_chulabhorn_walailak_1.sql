-- จาก "อาคารจุฬาภรณ์ 1" เป็น "อาคารจุฬาภรณวลัยลักษณ์ 1"
-- (ฐานข้อมูลใหม่ที่สร้างจาก init.sql จะใช้ชื่อใหม่อยู่แล้ว ไม่ต้องรันไฟล์นี้)

ALTER TABLE locations
    ALTER COLUMN building_name SET DEFAULT 'อาคารจุฬาภรณวลัยลักษณ์ 1';

UPDATE locations
SET building_name = 'อาคารจุฬาภรณวลัยลักษณ์ 1'
WHERE building_name = 'อาคารจุฬาภรณ์ 1';
